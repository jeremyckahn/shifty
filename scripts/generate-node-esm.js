/* eslint-env node */
/* eslint-disable @typescript-eslint/no-var-requires */

/**
 * Generates `dist/shifty.node.mjs`, a thin ES module wrapper around the
 * CommonJS Node bundle (`dist/shifty.node.js`), plus `dist/shifty.node.d.mts`,
 * its type declarations.
 *
 * Node cannot statically detect the named exports of a webpack UMD bundle, so
 * `import { tween } from 'shifty'` would fail without this wrapper. The export
 * list is read from the built bundle itself so it can never fall out of sync
 * with `src/index.ts`.
 */
const fs = require('fs')
const path = require('path')

const distDir = path.join(__dirname, '..', 'dist')
const cjsFile = 'shifty.node.js'
const esmFile = 'shifty.node.mjs'
const esmTypesFile = 'shifty.node.d.mts'

const exportedNames = Object.keys(require(path.join(distDir, cjsFile)))

const invalidName = exportedNames.find(
  name => !/^[A-Za-z_$][\w$]*$/.test(name) || name === 'default'
)

if (invalidName) {
  throw new Error(
    `Cannot generate an ESM named export for "${invalidName}" from ${cjsFile}`
  )
}

const contents = [
  `// Generated by scripts/generate-node-esm.js. Do not edit.`,
  `import shifty from './${cjsFile}'`,
  ``,
  `export default shifty`,
  ``,
  ...exportedNames.map(name => `export const ${name} = shifty.${name}`),
  ``,
].join('\n')

fs.writeFileSync(path.join(distDir, esmFile), contents)

// TypeScript treats `.d.ts` files as CommonJS in this package, so ESM importers
// need their own `.d.mts` declaring the ES module shape (named exports plus a
// default export of the whole module, matching the wrapper above).
const typesContents = [
  `// Generated by scripts/generate-node-esm.js. Do not edit.`,
  `import * as shifty from './index.js'`,
  ``,
  `export * from './index.js'`,
  `export default shifty`,
  ``,
].join('\n')

fs.writeFileSync(path.join(distDir, esmTypesFile), typesContents)

console.log(`Wrote dist/${esmFile} (${exportedNames.length} named exports)`)
console.log(`Wrote dist/${esmTypesFile}`)
